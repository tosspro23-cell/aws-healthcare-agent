"""Regenerates a new entry at the top of docs/EVAL_HISTORY.md from a live
capability-eval run (see care_agent.eval) -- the same "regenerate a
checked-in doc from the live agent" pattern scripts/run_examples.py
already uses, applied to eval results instead of raw example output.

Run with: python scripts/update_eval_history.py
Or against an LLM narrator (costs real Bedrock tokens, not run in CI):
    CARE_AGENT_NARRATOR_BACKEND=bedrock python scripts/update_eval_history.py
"""

from __future__ import annotations

import os
from datetime import date
from pathlib import Path

from care_agent.eval import git_short_sha, run_eval, summarize

REPO_ROOT = Path(__file__).resolve().parent.parent
HISTORY_PATH = REPO_ROOT / "docs" / "EVAL_HISTORY.md"

_HEADER = """# Capability Eval History

Generated by `scripts/update_eval_history.py`, which runs
`care_agent.eval` (a curated, capability-labeled question set in
`data/sample_questions.json`) against the real agent and prepends a new
dated entry below. Newest entries at the top, the same convention
`docs/DECISIONS.md` uses. Run this after any change to `reasoning.py`,
`safety.py`, a narrator, or the question set itself, to see whether the
capabilities the questions document are still actually demonstrated by
the real agent -- not just described in a data file.

The default (and CI-gated, via `pytest`/`eval-capabilities`) run is
against the deterministic mock narrator, which costs nothing and is
fully reproducible. Run manually against
`CARE_AGENT_NARRATOR_BACKEND=bedrock` occasionally to confirm the same
capabilities hold for an LLM's free-form prose, not just the mock
narrator's fixed templates -- that run costs real Bedrock tokens, so
it's not part of CI.
"""


def _render_entry(summary) -> str:
    narrator_backend = summary.results[0].narrator_backend if summary.results else os.environ.get("CARE_AGENT_NARRATOR_BACKEND", "mock")
    lines = [f"## {date.today().isoformat()} — commit `{git_short_sha()}`, narrator: `{narrator_backend}`", ""]
    lines.append(
        f"**{summary.passed_checks}/{summary.total_checks} checks passed ({summary.pass_rate:.0%}), {summary.total_skipped} skipped.**"
    )
    lines.append("")
    lines.append("| Question | Result |")
    lines.append("|---|---|")
    for r in summary.results:
        badge = "PASS" if r.passed else "**FAIL**"
        note = f" ({len(r.skipped)} skipped)" if r.skipped else ""
        lines.append(f"| `{r.question_id}` | {badge}{note} |")

    failures = [(r.question_id, c.capability, c.detail) for r in summary.results for c in r.results if not c.passed]
    if failures:
        lines.append("")
        lines.append("**Failures:**")
        for question_id, capability, detail in failures:
            lines.append(f"- `{question_id}` / `{capability}`: {detail}")

    skipped = [(r.question_id, s) for r in summary.results for s in r.skipped]
    if skipped:
        lines.append("")
        lines.append("<details>")
        lines.append("<summary>Skipped capabilities (context-dependent, not automatically checkable)</summary>")
        lines.append("")
        for question_id, capability in skipped:
            lines.append(f"- `{question_id}`: {capability}")
        lines.append("")
        lines.append("</details>")

    return "\n".join(lines)


def main() -> None:
    results = run_eval()
    summary = summarize(results)

    existing = HISTORY_PATH.read_text(encoding="utf-8") if HISTORY_PATH.exists() else _HEADER + "\n---\n"
    marker = "\n---\n"
    if marker in existing:
        header, _, rest = existing.partition(marker)
    else:
        header, rest = existing, ""

    new_entry = _render_entry(summary)
    content = header.rstrip("\n") + "\n\n---\n" + new_entry + "\n\n---\n" + rest.lstrip("\n")
    HISTORY_PATH.write_text(content, encoding="utf-8")
    print(f"Wrote a new entry to {HISTORY_PATH} ({summary.passed_checks}/{summary.total_checks} passed)")
    if not os.environ.get("CARE_AGENT_NARRATOR_BACKEND"):
        print("(ran against the default mock narrator; set CARE_AGENT_NARRATOR_BACKEND=bedrock to eval an LLM narrator instead)")


if __name__ == "__main__":
    main()
